//! One slash command graph → one module (D-057).

use std::collections::BTreeSet;

use proc_macro2::TokenStream;
use quote::{format_ident, quote};
use rustbot_core::registry::{CommandOption, DataType, is_id};
use rustbot_core::template::{self, Segment};
use rustbot_core::{Graph, GraphFile, NodeId, PinRef, Registry};
use serde_json::Value;

use crate::Error;
use crate::event::Event;

/// The module for a validated command graph.
pub(crate) fn module(file: &GraphFile, registry: &Registry) -> Result<TokenStream, Error> {
    let graph = &file.graph;
    let no_codegen = |id: &NodeId| Error::NoCodegen {
        graph: file.name.clone(),
        node: id.clone(),
        kind: graph.nodes[id].kind.clone(),
    };
    // Validation guarantees exactly one trigger.
    let (trigger, node) = graph
        .nodes
        .iter()
        .find(|(_, node)| {
            registry
                .get(&node.kind)
                .is_some_and(|t| t.category == rustbot_core::registry::Category::Trigger)
        })
        .expect("a validated graph has a trigger");
    if node.kind != "core.slash_command" {
        return Err(no_codegen(trigger));
    }
    let name = text(graph, trigger, "name");
    let description = text(graph, trigger, "description");
    let options = CommandOption::list(node.props.get("options"));
    let option_builders = options.iter().map(option_builder);
    let gate = gate(&file.graph, registry);
    // Discord takes one reply to a command; later ones are follow-ups.
    let follow_ups = graph
        .nodes
        .values()
        .filter(|n| n.kind == "core.reply")
        .count()
        > 1;
    let mut code = Body {
        follow_ups,
        file,
        options: &options,
        vars: BTreeSet::new(),
        quiet: false,
        interaction: false,
        command: name,
        event: None,
        path: Vec::new(),
    };
    let body = code.after(trigger, "then")?;
    let Body {
        vars,
        quiet: needs_quiet,
        interaction: needs_interaction,
        ..
    } = code;

    let bindings = vars.iter().map(|path| binding(path, &options));
    // The guild, channel and member are on the interaction; `cmd` itself is the command data,
    // which holds the options.
    let interaction = (needs_interaction || vars.iter().any(|path| !path.starts_with("option.")))
        .then(|| quote!(let interaction = cmd.interaction();));
    let replied = follow_ups.then(|| quote!(let replied = std::cell::Cell::new(false);));
    let author = vars
        .iter()
        .any(|path| path.starts_with("user."))
        .then(|| quote!(let author = interaction.author().ok_or("the command has no user")?;));
    // With @everyone allowed in a message, the same text from users must not trigger it.
    let quiet = needs_quiet.then(quiet_fn);
    let doc = format!(
        " The `/{name}` command, from `graphs/commands/{}.json`.",
        file.name
    );
    Ok(quote! {
        #![doc = #doc]
        #![doc = " Generated by RustBot Creator: do not edit, it is overwritten."]
        // Nested conditions mirror the graph's branches.
        #![allow(clippy::collapsible_if, clippy::collapsible_else_if)]

        use djs_rs::builders::{SlashCommandBuilder, ValidationError};
        use djs_rs::model::rest::CreateApplicationCommand;
        use djs_rs::prelude::*;

        pub(crate) fn definition() -> Result<CreateApplicationCommand, ValidationError> {
            SlashCommandBuilder::new(#name, #description)
                #(#option_builders)*
                #gate
                .build()
        }

        #quiet

        pub(crate) fn register(client: &Client) {
            client.command(#name, |ctx, cmd| async move {
                #interaction
                #author
                #replied
                #(#bindings)*
                #body
                Ok(())
            });
        }
    })
}

/// `.default_member_permissions(…)`: members without the permissions of the command's
/// gated actions do not see it (D-085).
fn gate(graph: &Graph, registry: &Registry) -> Option<TokenStream> {
    let permissions: BTreeSet<&str> = graph
        .nodes
        .values()
        .filter_map(|node| registry.needed_permission(node))
        .collect();
    (!permissions.is_empty()).then(|| {
        let flags = permissions
            .iter()
            .map(|permission| format_ident!("{}", permission.to_uppercase()));
        quote!(.default_member_permissions(#(djs_rs::model::permissions::Permissions::#flags)|*))
    })
}

/// `quiet()`, for messages with `@everyone` typed in: text from users that cannot form
/// `@everyone` or `@here` (C-016).
pub(crate) fn quiet_fn() -> TokenStream {
    quote! {
        /// Text from users, unable to form `@everyone` or `@here`, for messages whose
        /// author allowed them (C-016). A zero-width space follows every `@` and leads
        /// the value, so it cannot join the text around it into a mention either.
        fn quiet(text: &dyn std::fmt::Display) -> String {
            let text = text.to_string().replace('@', "@\u{200b}");
            format!("\u{200b}{text}")
        }
    }
}

/// A graph's body, built from its trigger along the flow wires.
pub(crate) struct Body<'a> {
    file: &'a GraphFile,
    /// More than one "Reply": each checks `replied` to reply or follow up.
    follow_ups: bool,
    options: &'a [CommandOption],
    /// The template variables used, which become `let`s at the top.
    vars: BTreeSet<String>,
    /// Some message needs `quiet()` (C-016).
    quiet: bool,
    /// Some node reads the interaction: the author's member data, the server.
    interaction: bool,
    /// The command's name, for Logs.
    command: &'a str,
    /// The event an event graph starts from; `None` in a command (D-091).
    event: Option<Event>,
    /// The nodes from the trigger to here, to find loops.
    path: Vec<NodeId>,
}

impl<'a> Body<'a> {
    /// The body of an event graph (D-091).
    pub(crate) fn for_event(file: &'a GraphFile, event: Event) -> Self {
        Body {
            follow_ups: false,
            file,
            options: &[],
            vars: BTreeSet::new(),
            quiet: false,
            interaction: false,
            command: &file.name,
            event: Some(event),
            path: Vec::new(),
        }
    }

    /// The variables the code uses and whether it needs `quiet()`.
    pub(crate) fn finish(self) -> (BTreeSet<String>, bool) {
        (self.vars, self.quiet)
    }

    /// The code of the nodes wired to `pin` of `id`, one after another in edge order.
    pub(crate) fn after(&mut self, id: &NodeId, pin: &str) -> Result<TokenStream, Error> {
        let mut code = TokenStream::new();
        for next in self.next(id, pin) {
            self.chain(&next, &mut code)?;
        }
        Ok(code)
    }

    /// The nodes wired to `pin` of `id`, in edge order.
    fn next(&self, id: &NodeId, pin: &str) -> Vec<NodeId> {
        let from = PinRef {
            node: id.clone(),
            pin: pin.to_owned(),
        };
        self.file
            .graph
            .edges
            .iter()
            .filter(|edge| edge.from == from)
            .map(|edge| edge.to.node.clone())
            .collect()
    }

    /// Appends `id`'s code and then what follows its "then", one after another, so a long
    /// chain is not nested, and copied, once per node.
    fn chain(&mut self, id: &NodeId, code: &mut TokenStream) -> Result<(), Error> {
        if self.path.contains(id) {
            return Err(Error::Cycle {
                graph: self.file.name.clone(),
                node: id.clone(),
            });
        }
        self.path.push(id.clone());
        let (own, then) = self.node(id)?;
        code.extend(own);
        if then {
            for next in self.next(id, "then") {
                self.chain(&next, code)?;
            }
        }
        self.path.pop();
        Ok(())
    }

    /// A node's code, its branches included, and whether its "then" follows it in the same
    /// block. A node that two branches lead to is generated in each of them.
    // shortcut: joins are copied, which grows with nested joins; share them as local
    // functions if graphs get big.
    fn node(&mut self, id: &NodeId) -> Result<(TokenStream, bool), Error> {
        let graph = &self.file.graph;
        let code = match graph.nodes[id].kind.as_str() {
            "core.reply" => (self.reply(id), true),
            // Validation allows it only after "New message" (D-094).
            "core.delete_message" => (
                quote!(ctx.messages(event.channel_id).delete(event.id).await?;),
                true,
            ),
            "core.send_message" => {
                let channel = self.channel(text(graph, id, "channel"));
                let message = self.message(id);
                let send = quote! {
                    ctx.messages(#channel)
                        .send(djs_rs::model::rest::CreateMessage::default() #message)
                        .await?;
                };
                (send, true)
            }
            "core.has_permission" | "core.has_role" | "core.compare" => {
                let yes = self.after(id, "yes")?;
                let no = self.after(id, "no")?;
                // A condition with nothing after it does nothing.
                let code = match (yes.is_empty(), no.is_empty()) {
                    (true, true) => TokenStream::new(),
                    (false, true) => {
                        let condition = self.condition(id);
                        quote!(if #condition { #yes })
                    }
                    (true, false) => {
                        let condition = self.condition(id);
                        quote!(if !(#condition) { #no })
                    }
                    (false, false) => {
                        let condition = self.condition(id);
                        quote!(if #condition { #yes } else { #no })
                    }
                };
                (code, false)
            }
            "core.ban" | "core.kick" | "core.timeout" | "core.add_role" | "core.remove_role" => {
                self.moderate(id)?
            }
            _ => {
                return Err(Error::NoCodegen {
                    graph: self.file.name.clone(),
                    node: id.clone(),
                    kind: graph.nodes[id].kind.clone(),
                });
            }
        };
        Ok(code)
    }

    /// A reply, or a follow-up if the command replied already (D-086).
    fn reply(&mut self, id: &NodeId) -> TokenStream {
        let graph = &self.file.graph;
        let mut message = self.message(id);
        if self.event.is_some() {
            // In "New message", a reply to that message (D-094).
            return quote! {
                event
                    .reply(&ctx, djs_rs::model::rest::CreateMessage::default() #message)
                    .await?;
            };
        }
        // Only the author sees it (D-086).
        if graph.nodes[id].props.get("private") == Some(&Value::Bool(true)) {
            message.extend(quote!(.ephemeral()));
        }
        let reply = quote! {
            cmd.reply(
                &ctx,
                djs_rs::model::interaction::MessageCallbackData::default() #message,
            )
            .await?;
        };
        if self.follow_ups {
            quote! {
                if replied.replace(true) {
                    cmd.follow_up(
                        &ctx,
                        djs_rs::model::rest::CreateFollowupMessage::default() #message,
                    )
                    .await?;
                } else {
                    #reply
                }
            }
        } else {
            reply
        }
    }

    /// A moderation action, then "then" or, on failure, "error" (D-082).
    fn moderate(&mut self, id: &NodeId) -> Result<(TokenStream, bool), Error> {
        self.interaction = true;
        let action = self.action(id);
        let error = self.after(id, "error")?;
        let command = self.command;
        if error.is_empty() {
            // A failure ends the command, and djs-rs logs it (D-082).
            return Ok((quote!({ #action }), true));
        }
        let then = self.after(id, "then")?;
        Ok((
            {
                // A command is `/ban`, an event graph its file name.
                let slash = if self.event.is_some() { "" } else { "/" };
                let log = format!(
                    "WARN {slash}{}: {{error}}",
                    command.replace('{', "{{").replace('}', "}}")
                );
                let log = quote!(eprintln!(#log););
                let handle = if then.is_empty() {
                    quote!(if let Err(error) = result { #log #error })
                } else {
                    quote! {
                        match result {
                            Ok(()) => { #then }
                            Err(error) => { #log #error }
                        }
                    }
                };
                quote! {
                    let result: Result<(), Box<dyn std::error::Error + Send + Sync>> = async {
                        #action
                        Ok(())
                    }
                    .await;
                    #handle
                }
            },
            false,
        ))
    }

    /// A condition node's test, a `bool` (D-077).
    fn condition(&mut self, id: &NodeId) -> TokenStream {
        let graph = &self.file.graph;
        match graph.nodes[id].kind.as_str() {
            "core.has_permission" => {
                let member = self.member(text(graph, id, "user"));
                let flag = format_ident!("{}", text(graph, id, "permission").to_uppercase());
                // Administrators have every permission.
                quote! {
                    #member.is_some_and(|member| member.permissions.intersects(
                        djs_rs::model::permissions::Permissions::#flag
                            | djs_rs::model::permissions::Permissions::ADMINISTRATOR,
                    ))
                }
            }
            "core.has_role" => {
                let roles = self.roles(text(graph, id, "user"));
                let role = self.role(text(graph, id, "role"));
                quote!(#roles.zip(#role).is_some_and(|(roles, role)| roles.contains(&role)))
            }
            "core.compare" => {
                let left =
                    template_expr(text(graph, id, "left"), self.options, false, &mut self.vars);
                let right = template_expr(
                    text(graph, id, "right"),
                    self.options,
                    false,
                    &mut self.vars,
                );
                // Letter case does not matter (D-081); numbers compare as numbers.
                let number = |op: TokenStream| {
                    quote! {
                        #left.trim().parse::<f64>().ok()
                            .zip(#right.trim().parse::<f64>().ok())
                            .is_some_and(|(left, right)| left #op right)
                    }
                };
                match text(graph, id, "operator") {
                    "equals" => quote!(#left.to_lowercase() == #right.to_lowercase()),
                    "not_equals" => quote!(#left.to_lowercase() != #right.to_lowercase()),
                    "contains" => quote!(#left.to_lowercase().contains(&#right.to_lowercase())),
                    "greater" => number(quote!(>)),
                    "less" => number(quote!(<)),
                    other => {
                        unreachable!("validation only lets known operators through, not {other}")
                    }
                }
            }
            other => unreachable!("{other} is not a condition"),
        }
    }

    /// A user field's member data on this server, an `Option<&InteractionMember>`.
    fn member(&mut self, user: &str) -> TokenStream {
        if user == "user" {
            self.interaction = true;
            return quote!(interaction.member.as_ref());
        }
        let (_, option, _) = option_path(user, self.options).expect("validated variable");
        let name = &option.name;
        quote!(cmd.get_member(#name).map(|(_, member)| member))
    }

    /// A moderation action's call to Discord, which `?` ends on failure (D-073, D-082).
    fn action(&mut self, id: &NodeId) -> TokenStream {
        let graph = &self.file.graph;
        let user = match text(graph, id, "user") {
            "user" if self.event.is_some() => self.event.expect("checked").user_id(),
            "user" => quote!(
                interaction
                    .author()
                    .map(|user| user.id)
                    .ok_or("the command has no user")?
            ),
            option => {
                let (_, option, _) = option_path(option, self.options).expect("validated variable");
                let (name, missing) = (
                    &option.name,
                    format!("the option {} was not given", option.name),
                );
                quote!(cmd.get_user(#name).map(|user| user.id).ok_or(#missing)?)
            }
        };
        let reason = self.reason(text(graph, id, "reason"));
        let call = match graph.nodes[id].kind.as_str() {
            "core.ban" => {
                let seconds: u32 = match text(graph, id, "delete_messages") {
                    "hour" => 3_600,
                    "day" => 86_400,
                    "week" => 604_800,
                    _ => 0,
                };
                let ban = if seconds == 0 {
                    quote!(djs_rs::model::rest::CreateGuildBan::default())
                } else {
                    quote! {{
                        let mut ban = djs_rs::model::rest::CreateGuildBan::default();
                        ban.delete_message_seconds = Some(#seconds);
                        ban
                    }}
                };
                quote!(members.ban(user, &#ban, #reason))
            }
            "core.kick" => quote!(members.kick(user, #reason)),
            "core.timeout" => {
                let minutes = template_expr(
                    text(graph, id, "minutes"),
                    self.options,
                    false,
                    &mut self.vars,
                );
                // Discord's longest timeout, as `core.timeout` allows (D-084).
                quote! {{
                    let minutes = #minutes
                        .trim()
                        .parse::<f64>()
                        .ok()
                        .filter(|minutes| *minutes > 0.0 && *minutes <= 40_320.0)
                        .ok_or("a timeout is more than 0 and at most 40320 minutes (28 days)")?;
                    let until = djs_rs::model::util::Timestamp::from_unix_micros(
                        djs_rs::model::util::Timestamp::now().as_unix_micros()
                            + (minutes * 60_000_000.0) as i64,
                    );
                    members.timeout(user, Some(until), #reason)
                }}
            }
            kind @ ("core.add_role" | "core.remove_role") => {
                let role = match text(graph, id, "role") {
                    role if is_id(role) => {
                        let id: u64 = role.parse().expect("validated ID");
                        quote!(djs_rs::model::id::RoleId::new(#id))
                    }
                    role => {
                        let (_, option, _) =
                            option_path(role, self.options).expect("validated variable");
                        let (name, missing) = (
                            &option.name,
                            format!("the option {} was not given", option.name),
                        );
                        quote!(cmd.get_role(#name).map(|role| role.id).ok_or(#missing)?)
                    }
                };
                let method = format_ident!("{}", kind.trim_start_matches("core."));
                quote!(members.#method(user, #role, #reason))
            }
            other => unreachable!("{other} is not a moderation action"),
        };
        let guild = self.event.map_or_else(
            || {
                quote!(
                    interaction
                        .guild_id
                        .ok_or("the command was not used on a server")?
                )
            },
            |event| {
                let guild = event.guild_id();
                quote!(#guild.ok_or("the event did not come from a server")?)
            },
        );
        quote! {
            let members = ctx.members(#guild);
            let user = #user;
            #call.await?;
        }
    }

    /// A message's builder calls: its text with the mentions it may make (C-016), and its
    /// embed (D-087).
    fn message(&mut self, id: &NodeId) -> TokenStream {
        let file = self.file;
        let template = text(&file.graph, id, "content");
        let mut message = TokenStream::new();
        if !template.trim().is_empty() {
            let everyone = mentions_everyone(template);
            self.quiet |= everyone;
            let content = template_expr(template, self.options, everyone, &mut self.vars);
            let event = self.event;
            let author = || event.map_or_else(|| quote!(author.id), Event::user_id);
            let mentions = allowed_mentions(template, self.options, everyone, &author);
            message.extend(quote!(.content(#content).allowed_mentions(#mentions)));
        }
        message.extend(self.embed(id));
        message
    }

    /// A message's `.embed(…)`, if it has a title or description (D-079, D-087). A field
    /// whose variables come out empty is left out, and so is a colour that is not one.
    fn embed(&mut self, id: &NodeId) -> Option<TokenStream> {
        let file = self.file;
        let field = |name| text(&file.graph, id, name);
        if field("embed_title").trim().is_empty() && field("embed_description").trim().is_empty() {
            return None;
        }
        let mut steps = Vec::new();
        for (name, method) in [
            ("embed_title", "title"),
            ("embed_description", "description"),
            ("embed_image", "image"),
            ("embed_footer", "footer"),
        ] {
            let template = field(name);
            if template.trim().is_empty() {
                continue;
            }
            let literal = is_literal(template);
            let value = template_expr(template, self.options, false, &mut self.vars);
            let set = |value: TokenStream| {
                let method = format_ident!("{method}");
                if method == "footer" {
                    quote!(embed.footer(djs_rs::builders::EmbedFooterBuilder::new(#value)))
                } else {
                    quote!(embed.#method(#value))
                }
            };
            steps.push(if literal {
                let set = set(value);
                quote!(let embed = #set;)
            } else {
                let set = set(quote!(value));
                quote! {
                    let value = #value;
                    let embed = if value.is_empty() { embed } else { #set };
                }
            });
        }
        let color = field("embed_color").trim();
        if let Some(hex) = color.strip_prefix('#').filter(|_| is_literal(color)) {
            let color = u32::from_str_radix(hex, 16).expect("validated colour");
            steps.push(quote!(let embed = embed.color(#color);));
        } else if !color.is_empty() {
            let value = template_expr(color, self.options, false, &mut self.vars);
            steps.push(quote! {
                let embed = match u32::from_str_radix(#value.trim().trim_start_matches('#'), 16) {
                    Ok(color) if color <= 0xFF_FFFF => embed.color(color),
                    _ => embed,
                };
            });
        }
        Some(quote! {
            .embed({
                let embed = djs_rs::builders::EmbedBuilder::new();
                #(#steps)*
                embed.build()?
            })
        })
    }

    /// A channel field's channel, a `ChannelId`: the command's, an option, or an ID (D-088).
    fn channel(&mut self, channel: &str) -> TokenStream {
        if let (Some(event), "channel") = (self.event, channel) {
            return event.channel_id();
        }
        if channel == "channel" {
            self.interaction = true;
            return quote!(interaction.channel_id.ok_or("the command has no channel")?);
        }
        if is_id(channel) {
            let id: u64 = channel.parse().expect("validated ID");
            return quote!(djs_rs::model::id::ChannelId::new(#id));
        }
        let (_, option, _) = option_path(channel, self.options).expect("validated variable");
        let (name, missing) = (
            &option.name,
            format!("the option {} was not given", option.name),
        );
        quote!(cmd.get_channel(#name).map(|channel| channel.id).ok_or(#missing)?)
    }

    /// An audit log reason, an `Option<&str>`; none when the field is empty.
    fn reason(&mut self, reason: &str) -> TokenStream {
        match reason {
            "" => quote!(None),
            reason => {
                let literal = is_literal(reason);
                let reason = template_expr(reason, self.options, false, &mut self.vars);
                if literal {
                    quote!(Some(#reason))
                } else {
                    quote!(Some(#reason).as_deref())
                }
            }
        }
    }

    /// A user field's roles, an `Option<&Vec<RoleId>>`.
    fn roles(&mut self, user: &str) -> TokenStream {
        match (self.event, user) {
            (Some(event), _) => event.roles(),
            (None, "user") => {
                self.interaction = true;
                quote!(
                    interaction
                        .member
                        .as_ref()
                        .map(|member| &member.member.roles)
                )
            }
            (None, option) => {
                let (_, option, _) = option_path(option, self.options).expect("validated variable");
                let name = &option.name;
                quote!(cmd.get_member(#name).map(|(_, member)| &member.member.roles))
            }
        }
    }

    /// A role field's role, an `Option<RoleId>`: a fixed ID or a role option (D-080).
    fn role(&self, role: &str) -> TokenStream {
        if is_id(role) {
            let id: u64 = role.parse().expect("validated ID");
            return quote!(Some(djs_rs::model::id::RoleId::new(#id)));
        }
        let (_, option, _) = option_path(role, self.options).expect("validated variable");
        let name = &option.name;
        quote!(cmd.get_role(#name).map(|role| role.id))
    }
}

/// A text prop. Validation guarantees required props are strings.
/// Whether a template has no variables, so its Rust expression is a string literal.
fn is_literal(template: &str) -> bool {
    rustbot_core::template::parse(template).is_ok_and(|segments| {
        segments
            .iter()
            .all(|s| matches!(s, rustbot_core::template::Segment::Text(_)))
    })
}

fn text<'a>(graph: &'a Graph, id: &NodeId, prop: &str) -> &'a str {
    match graph.nodes[id].props.get(prop) {
        Some(Value::String(s)) => s,
        _ => "",
    }
}

/// A template as a Rust expression: a string literal, or `format!` with one argument per
/// variable. Literal braces are doubled, so the text can never become a format directive.
fn template_expr(
    text: &str,
    options: &[CommandOption],
    quiet: bool,
    vars: &mut BTreeSet<String>,
) -> TokenStream {
    let segments = template::parse(text).expect("validated templates parse");
    let mut format = String::new();
    let mut args = Vec::new();
    for segment in segments {
        match segment {
            Segment::Text(s) => format.push_str(&s.replace('{', "{{").replace('}', "}}")),
            Segment::Var(path) => {
                let path = path.join(".");
                format.push_str("{}");
                let var = ident(&path, options);
                // Mentions are `<@id>` built by the bot, and must stay intact to notify.
                args.push(if quiet && !is_mention(&path, options) {
                    quote!(quiet(&#var))
                } else {
                    quote!(#var)
                });
                vars.insert(path);
            }
        }
    }
    match args.as_slice() {
        [] => quote!(#text),
        // Only a variable: its text, without a format! that clippy calls useless.
        [only] if format == "{}" => quote!(#only.to_string()),
        _ => quote!(format!(#format, #(#args),*)),
    }
}

/// Who a message may notify: only the mentions its author wrote. A `{….mention}` variable
/// notifies its user or role, and `@everyone`/`@here` work only typed into the template. Text
/// from users, such as a text option or a nickname, never notifies anyone, so
/// `/ban reason:@everyone` cannot ping the server.
fn allowed_mentions(
    template: &str,
    options: &[CommandOption],
    everyone: bool,
    author: &dyn Fn() -> TokenStream,
) -> TokenStream {
    let segments = template::parse(template).expect("validated templates parse");
    let mut add = Vec::new();
    for segment in &segments {
        match segment {
            Segment::Text(_) => {}
            Segment::Var(path) if path.join(".") == "user.mention" => {
                let author = author();
                add.push(quote!(mentions.users.push(#author);));
            }
            Segment::Var(path) => {
                let path = path.join(".");
                if let Some((_, option, Some("mention"))) = option_path(&path, options) {
                    let name = &option.name;
                    add.push(match option.ty {
                        DataType::User => {
                            quote!(mentions.users.extend(cmd.get_user(#name).map(|user| user.id));)
                        }
                        DataType::Role => {
                            quote!(mentions.roles.extend(cmd.get_role(#name).map(|role| role.id));)
                        }
                        // Channel mentions notify no one.
                        _ => continue,
                    });
                }
            }
        }
    }
    if everyone {
        add.push(quote! {
            mentions
                .parse
                .push(djs_rs::model::message::AllowedMentionType::Everyone);
        });
    }
    if add.is_empty() {
        return quote!(djs_rs::model::message::AllowedMentions::default());
    }
    quote!({
        let mut mentions = djs_rs::model::message::AllowedMentions::default();
        #(#add)*
        mentions
    })
}

/// Whether the variable is a mention the bot builds, `<@id>`, `<@&id>` or `<#id>`, rather
/// than text that could come from users. Decided by the variable, not by its name's ending:
/// a text option may be called `mention`.
fn is_mention(path: &str, options: &[CommandOption]) -> bool {
    match option_path(path, options) {
        Some((_, option, field)) => {
            field == Some("mention")
                && matches!(
                    option.ty,
                    DataType::User | DataType::Channel | DataType::Role
                )
        }
        None => matches!(path, "user.mention" | "channel.mention"),
    }
}

/// Whether the template's own text has `@everyone` or `@here`. Discord allows both or
/// neither, so the variables' values are then made harmless with `quiet`.
fn mentions_everyone(template: &str) -> bool {
    template::parse(template)
        .expect("validated templates parse")
        .iter()
        .any(|segment| match segment {
            Segment::Text(text) => text.contains("@everyone") || text.contains("@here"),
            Segment::Var(_) => false,
        })
}

/// The local holding a variable: `user.name` → `user_name`. Paths are validated against the
/// registry's fixed field names, so they are always identifiers. An option is named by its
/// position, `option.target.name` → `option_0_name`, since option names are free text.
fn ident(path: &str, options: &[CommandOption]) -> proc_macro2::Ident {
    if let Some((ix, _, field)) = option_path(path, options) {
        return match field {
            Some(field) => format_ident!("option_{ix}_{field}"),
            None => format_ident!("option_{ix}"),
        };
    }
    format_ident!("{}", path.replace('.', "_"))
}

/// `option.<name>[.<field>]` as the option's position, the option and the field.
fn option_path<'a, 'p>(
    path: &'p str,
    options: &'a [CommandOption],
) -> Option<(usize, &'a CommandOption, Option<&'p str>)> {
    let rest = path.strip_prefix("option.")?;
    let (name, field) = rest
        .split_once('.')
        .map_or((rest, None), |(name, field)| (name, Some(field)));
    let ix = options.iter().position(|option| option.name == name)?;
    Some((ix, &options[ix], field))
}

/// `.option(…)` adding an option to the command's definition (D-076).
fn option_builder(option: &CommandOption) -> TokenStream {
    let builder = match option.ty {
        DataType::Text => quote!(SlashCommandStringOption),
        DataType::Number => quote!(SlashCommandNumberOption),
        DataType::Bool => quote!(SlashCommandBooleanOption),
        DataType::User => quote!(SlashCommandUserOption),
        DataType::Channel => quote!(SlashCommandChannelOption),
        DataType::Role => quote!(SlashCommandRoleOption),
        DataType::Server => unreachable!("validation refuses server options"),
    };
    let (name, description, required) = (&option.name, &option.description, option.required);
    quote!(.option(djs_rs::builders::#builder::new(#name, #description).required(#required)))
}

/// An option's value as text; empty when an optional option is not filled in.
fn option_value(option: &CommandOption, field: Option<&str>) -> TokenStream {
    let name = &option.name;
    let unknown = || unreachable!("validation only lets known fields through, not {field:?}");
    match (option.ty, field) {
        (DataType::Text, None) => quote!(cmd.get_string(#name).unwrap_or_default()),
        (DataType::Number, None) => {
            quote!(cmd.get_number(#name).map(|n| n.to_string()).unwrap_or_default())
        }
        (DataType::Bool, None) => {
            quote!(cmd.get_boolean(#name).map(|b| b.to_string()).unwrap_or_default())
        }
        (DataType::User, Some(field)) => {
            let value = match field {
                "id" => quote!(user.id.to_string()),
                "username" => quote!(user.username.to_string()),
                "display_name" => quote!(user.display_name().to_string()),
                "mention" => quote!(djs_rs::formatters::user_mention(user.id).to_string()),
                // What people see in the chat: nickname, then display name (D-054).
                "name" => quote! {
                    cmd.get_member(#name)
                        .and_then(|(_, member)| member.member.nick.as_deref())
                        .unwrap_or_else(|| user.display_name())
                        .to_string()
                },
                _ => unknown(),
            };
            quote!(cmd.get_user(#name).map(|user| #value).unwrap_or_default())
        }
        (DataType::Channel, Some(field)) => {
            let value = match field {
                "id" => quote!(channel.id.to_string()),
                "name" => quote!(channel.name.as_deref().unwrap_or_default().to_string()),
                "mention" => quote!(djs_rs::formatters::channel_mention(channel.id).to_string()),
                _ => unknown(),
            };
            quote!(cmd.get_channel(#name).map(|channel| #value).unwrap_or_default())
        }
        (DataType::Role, Some(field)) => {
            let value = match field {
                "id" => quote!(role.id.to_string()),
                "name" => quote!(role.name.to_string()),
                "mention" => quote!(djs_rs::formatters::role_mention(role.id).to_string()),
                _ => unknown(),
            };
            quote!(cmd.get_role(#name).map(|role| #value).unwrap_or_default())
        }
        _ => unknown(),
    }
}

/// The `let` that computes a variable from the interaction (D-053, D-054).
fn binding(path: &str, options: &[CommandOption]) -> TokenStream {
    let name = ident(path, options);
    if let Some((_, option, field)) = option_path(path, options) {
        let value = option_value(option, field);
        return quote!(let #name = #value;);
    }
    let value = match path {
        "user.id" => quote!(author.id),
        "user.username" => quote!(&author.username),
        "user.display_name" => quote!(author.display_name()),
        // What people see in the chat: nickname, then display name, then username.
        "user.name" => quote! {
            interaction.member
                .as_ref()
                .and_then(|member| member.member.nick.as_deref())
                .unwrap_or_else(|| author.display_name())
        },
        "user.mention" => quote!(djs_rs::formatters::user_mention(author.id)),
        "channel.id" => quote!(
            interaction
                .channel_id
                .map(|id| id.to_string())
                .unwrap_or_default()
        ),
        "channel.name" => quote! {
            interaction.channel.as_ref().and_then(|channel| channel.name.as_deref()).unwrap_or_default()
        },
        "channel.mention" => quote! {
            interaction.channel_id
                .map(|id| djs_rs::formatters::channel_mention(id).to_string())
                .unwrap_or_default()
        },
        "server.id" => quote!(
            interaction
                .guild_id
                .map(|id| id.to_string())
                .unwrap_or_default()
        ),
        "server.name" => quote! {
            match interaction.guild_id {
                Some(id) => ctx.guilds().fetch(id).await?.name.to_string(),
                None => String::new(),
            }
        },
        other => unreachable!("validation only lets known variables through, not {other}"),
    };
    quote!(let #name = #value;)
}
