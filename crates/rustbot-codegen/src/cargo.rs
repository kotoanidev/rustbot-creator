//! `generated/Cargo.toml` (D-059), serialized rather than formatted, so values from
//! `project.toml` cannot inject TOML.

use rustbot_core::Manifest;
use serde::Serialize;

#[derive(Serialize)]
struct CargoToml<'a> {
    package: Package<'a>,
    /// Empty: the bot is its own workspace, even inside another one.
    workspace: Empty,
    /// The program, when it is not `src/main.rs`: an export's (D-175).
    #[serde(skip_serializing_if = "Vec::is_empty")]
    bin: Vec<Bin<'a>>,
    dependencies: Dependencies<'a>,
}

// The bools are Cargo.toml keys, not state.
#[allow(clippy::struct_excessive_bools)]
#[derive(Serialize)]
struct Package<'a> {
    name: &'a str,
    version: &'static str,
    edition: &'static str,
    publish: bool,
    #[serde(skip_serializing_if = "str::is_empty")]
    license: &'a str,
    // Nothing runs at build time and nothing is picked up by file name: the bot is exactly
    // the generated files, even if someone drops a `build.rs` or `examples/` next to them.
    build: bool,
    autoexamples: bool,
    autotests: bool,
    autobenches: bool,
    /// Off in an export, whose `src/` is the user's code, not more programs or a library.
    #[serde(skip_serializing_if = "Option::is_none")]
    autobins: Option<bool>,
    #[serde(skip_serializing_if = "Option::is_none")]
    autolib: Option<bool>,
}

#[derive(Serialize)]
struct Bin<'a> {
    name: &'a str,
    path: &'static str,
}

#[derive(Serialize)]
struct Empty {}

#[derive(Serialize)]
struct Dependencies<'a> {
    #[serde(rename = "djs-rs")]
    djs_rs: Dependency<'a>,
    tokio: Dependency<'a>,
    #[serde(rename = "tracing-subscriber")]
    tracing_subscriber: Dependency<'a>,
    /// For the bot's memory (D-105); djs-rs brings it anyway.
    #[serde(skip_serializing_if = "Option::is_none")]
    serde_json: Option<Dependency<'a>>,
}

#[derive(Serialize)]
struct Dependency<'a> {
    version: String,
    #[serde(skip_serializing_if = "<[_]>::is_empty")]
    features: &'a [String],
}

/// `generated/Cargo.toml`, or with `export`, the `Cargo.toml` at an export's root, which
/// builds `generated/src/main.rs` beside the user's `src/` (D-175).
pub(crate) fn manifest(manifest: &Manifest, export: bool) -> String {
    let tokio = ["macros", "rt-multi-thread", "signal"].map(String::from);
    let tracing = ["env-filter".to_owned()];
    let cargo = CargoToml {
        package: Package {
            name: &manifest.bot.package,
            version: "0.1.0",
            edition: "2024",
            publish: false,
            license: &manifest.bot.license,
            build: false,
            autoexamples: false,
            autotests: false,
            autobenches: false,
            autobins: export.then_some(false),
            autolib: export.then_some(false),
        },
        workspace: Empty {},
        bin: if export {
            vec![Bin {
                name: &manifest.bot.package,
                path: "generated/src/main.rs",
            }]
        } else {
            Vec::new()
        },
        dependencies: Dependencies {
            // Pinned exactly: djs-rs is alpha and may break between alphas.
            djs_rs: Dependency {
                version: format!("={}", manifest.djs_rs.version),
                features: &manifest.djs_rs.features,
            },
            tokio: Dependency {
                version: "1".to_owned(),
                features: &tokio,
            },
            tracing_subscriber: Dependency {
                version: "0.3".to_owned(),
                features: &tracing,
            },
            serde_json: (!manifest.memory.is_empty()).then(|| Dependency {
                version: "1".to_owned(),
                features: &[],
            }),
        },
    };
    let body = toml::to_string(&cargo).expect("the bot's manifest always serializes to TOML");
    format!(
        "# Generated by RustBot Creator from project.toml: do not edit, it is overwritten.\n\n{body}"
    )
}
