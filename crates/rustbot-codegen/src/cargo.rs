//! `generated/Cargo.toml` (D-059), serialized rather than formatted, so values from
//! `project.toml` cannot inject TOML.

use rustbot_core::Manifest;
use serde::Serialize;

#[derive(Serialize)]
struct CargoToml<'a> {
    package: Package<'a>,
    /// Empty: the bot is its own workspace, even inside another one.
    workspace: Empty,
    dependencies: Dependencies<'a>,
}

#[derive(Serialize)]
struct Package<'a> {
    name: &'a str,
    version: &'static str,
    edition: &'static str,
    publish: bool,
    #[serde(skip_serializing_if = "str::is_empty")]
    license: &'a str,
}

#[derive(Serialize)]
struct Empty {}

#[derive(Serialize)]
struct Dependencies<'a> {
    #[serde(rename = "djs-rs")]
    djs_rs: Dependency<'a>,
    tokio: Dependency<'a>,
    #[serde(rename = "tracing-subscriber")]
    tracing_subscriber: Dependency<'a>,
}

#[derive(Serialize)]
struct Dependency<'a> {
    version: String,
    #[serde(skip_serializing_if = "<[_]>::is_empty")]
    features: &'a [String],
}

pub(crate) fn manifest(manifest: &Manifest) -> String {
    let tokio = ["macros", "rt-multi-thread", "signal"].map(String::from);
    let tracing = ["env-filter".to_owned()];
    let cargo = CargoToml {
        package: Package {
            name: &manifest.bot.package,
            version: "0.1.0",
            edition: "2024",
            publish: false,
            license: &manifest.bot.license,
        },
        workspace: Empty {},
        dependencies: Dependencies {
            // Pinned exactly: djs-rs is alpha and may break between alphas.
            djs_rs: Dependency {
                version: format!("={}", manifest.djs_rs.version),
                features: &manifest.djs_rs.features,
            },
            tokio: Dependency {
                version: "1".to_owned(),
                features: &tokio,
            },
            tracing_subscriber: Dependency {
                version: "0.3".to_owned(),
                features: &tracing,
            },
        },
    };
    let body = toml::to_string(&cargo).expect("the bot's manifest always serializes to TOML");
    format!(
        "# Generated by RustBot Creator from project.toml: do not edit, it is overwritten.\n\n{body}"
    )
}
